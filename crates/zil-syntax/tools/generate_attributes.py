#!/usr/bin/env python3
"""Generate the exact built-in attribute syntax registry from its normative JSON."""
import hashlib
import json
from pathlib import Path

crate = Path(__file__).resolve().parents[1]
source = crate.parents[1] / "spec" / "attributes.json"
raw = source.read_bytes()
data = json.loads(raw)
assert data["schema_version"] == 1
targets = {"item": "Item", "fn": "Function", "struct": "Struct", "enum": "Enum", "package": "Package", "field": "Field", "variant": "Variant", "parameter": "Parameter"}
repeat = {"and": "And", "concat": "Concat", "union": "Union", "error": "Error", "merge-unique-traits": "MergeUniqueTraits"}
arguments = {"config-expression": "Configuration", "enum(C,transparent)": "Representation", "positive-power-of-two-const": "Alignment", "trait-path-list": "TraitPaths", "optional-enum(always,never)": "OptionalInline", "string": "String", "registered-lint-list": "LintPaths", "none": "None"}
lines = ["// @generated by tools/generate_attributes.py from spec/attributes.json.", "// Do not silently edit registry rules in the implementation.", "use super::{ArgumentRule, AttributeTarget, BuiltinAttributeSpec, RepeatRule};", f'pub const REGISTRY_SHA256: &str = "{hashlib.sha256(raw).hexdigest()}";', "pub const BUILTIN_ATTRIBUTES: &[BuiltinAttributeSpec] = &["]
for attribute in data["attributes"]:
    target_list = ", ".join("AttributeTarget::" + targets[t] for t in attribute["targets"])
    lines.append("    BuiltinAttributeSpec { name: " + json.dumps(attribute["name"]) + f", phase: {attribute['phase']}, targets: &[{target_list}], repeat: RepeatRule::{repeat[attribute['repeat']]}, arguments: ArgumentRule::{arguments[attribute['args']]}" + " },")
lines.extend(["];", ""])
(crate / "src/attributes/registry.rs").write_text("\n".join(lines))
