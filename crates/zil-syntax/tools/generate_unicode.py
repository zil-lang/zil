#!/usr/bin/env python3
"""Generate the exact, pinned Unicode XID tables. Compiler builds need no Python.

Usage: python3 tools/generate_unicode.py /path/to/DerivedCoreProperties.txt
Data: https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt
"""
from pathlib import Path
import hashlib
import sys

VERSION = "17.0.0"
EXPECTED = "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"
data = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(data).hexdigest() == EXPECTED, "Unicode input hash mismatch"
properties = {"XID_Start": [], "XID_Continue": []}
for line in data.decode("utf-8").splitlines():
    value = line.split("#", 1)[0].strip()
    if not value or ";" not in value:
        continue
    interval, property_name = (part.strip() for part in value.split(";", 1))
    if property_name not in properties:
        continue
    bounds = interval.split("..")
    lo, hi = int(bounds[0], 16), int(bounds[-1], 16)
    ranges = properties[property_name]
    if ranges and ranges[-1][1] + 1 == lo:
        ranges[-1] = (ranges[-1][0], hi)
    else:
        ranges.append((lo, hi))

out = [
    "// Generated by tools/generate_unicode.py; do not edit ranges manually.",
    "// Unicode 17.0.0 DerivedCoreProperties.txt; © 2025 Unicode, Inc.",
    "// Source: https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt",
    f"// SHA256: {EXPECTED}",
    "// Distributed under the Unicode License (LICENSE-UNICODE).",
    f'pub const UNICODE_VERSION: &str = "{VERSION}";',
    "",
    "fn contains(ranges: &[(u32, u32)], c: char) -> bool {",
    "    let n = c as u32;",
    "    ranges.binary_search_by(|&(lo, hi)| {",
    "        if hi < n { std::cmp::Ordering::Less }",
    "        else if lo > n { std::cmp::Ordering::Greater }",
    "        else { std::cmp::Ordering::Equal }",
    "    }).is_ok()",
    "}",
    "",
    "pub fn is_xid_start(c: char) -> bool { c == '_' || contains(XID_START, c) }",
    "pub fn is_xid_continue(c: char) -> bool { contains(XID_CONTINUE, c) }",
    "",
]
for name, ranges in properties.items():
    out.append(f"const {name.upper()}: &[(u32, u32)] = &[")
    out.extend(f"    (0x{lo:X}, 0x{hi:X})," for lo, hi in ranges)
    out.append("];\n")
target = Path(__file__).resolve().parents[1] / "src/unicode.rs"
target.write_text("\n".join(out), encoding="utf-8")
print(f"Wrote {target}: " + ", ".join(f"{k}={len(v)} ranges" for k, v in properties.items()))
